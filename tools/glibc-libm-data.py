"""Write src/engine/libm-data.ts from glibc's math tables.

The tables are dumped as IEEE bit patterns by C programs compiled against
glibc 2.43's own data files (extract/glibc/build/dumptables*.c), so the values
are exactly the ones glibc's libm uses.

    python3 -I tools/glibc-libm-data.py <tables.json>... > src/engine/libm-data.ts
"""

import json
import struct
import sys


def dbl(h):
    return struct.unpack(">d", bytes.fromhex(h))[0]


def num(h):
    v = dbl(h)
    r = repr(v)
    return r if r not in ("inf", "-inf", "nan") else {"inf": "Infinity", "-inf": "-Infinity", "nan": "NaN"}[r]


def doubles(name, hexes):
    body = ",".join(num(h) for h in hexes)
    return f"export const {name} = new Float64Array([{body}]);\n"


def main():
    data = {}
    for path in sys.argv[1:]:
        with open(path) as f:
            data.update(json.load(f))
    out = [
        "// Generated by tools/glibc-libm-data.py from glibc 2.43's math tables. Do not edit.\n",
        "// The tables are the GNU C Library's (LGPL 2.1 or later; see libm.ts).\n",
        "/* eslint-disable */\n",
    ]
    for fam, fields in data.items():
        for key, val in fields.items():
            name = f"{fam.upper()}_{key.upper()}"
            if fam == "exp" and key == "tab":
                # uint64 pairs: tail bits (as a double) and scale bits (hi/lo words).
                tail = [val[2 * i] for i in range(128)]
                sb = [int(val[2 * i + 1], 16) for i in range(128)]
                out.append(doubles("EXP_TAIL", tail))
                out.append("export const EXP_SBITS_HI = new Uint32Array([" + ",".join(str(v >> 32) for v in sb) + "]);\n")
                out.append("export const EXP_SBITS_LO = new Uint32Array([" + ",".join(str(v & 0xFFFFFFFF) for v in sb) + "]);\n")
            elif isinstance(val, list):
                if val and isinstance(val[0], list):
                    flat = [h for row in val for h in row]
                    out.append(doubles(name, flat))
                else:
                    out.append(doubles(name, val))
            else:
                out.append(f"export const {name} = {num(val)};\n")
    sys.stdout.write("".join(out))


main()
